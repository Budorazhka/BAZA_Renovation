// Для каждого переведённого текстового узла помним исходник и наш перевод:
// по переводу мы узнаём, что значение в узле поставили мы, а не React.
const textOriginals = new WeakMap<Text, { original: string; translated: string }>()
const OBSERVER_KEY = '__bz26RuntimeI18nObserver__'
const ATTRS = ['placeholder', 'title', 'aria-label', 'alt'] as const

type RuntimeWindow = Window & {
  [OBSERVER_KEY]?: MutationObserver
}

function translateValue(value: string, language: Language): string {
  const exactMaps: Record<string, Record<string, string>> = { en: exactEn, ka: exactKa, es: exactEs, tr: exactTr }
  const replMaps: Record<string, [RegExp, string][]> = { en: replacements, ka: replacementsKa, es: replacementsEs, tr: replacementsTr }

  const normalized = value.replace(/\s+/g, ' ').trim()
  if (!normalized) return value
  const exact = exactMaps[language]?.[normalized]
  if (exact) return value.replace(normalized, exact)
  let translated = normalized
  const currentReplacements = replMaps[language] || []
  for (const [pattern, replacement] of currentReplacements) {
    pattern.lastIndex = 0
    if (pattern.test(translated)) {
      pattern.lastIndex = 0
      translated = translated.replace(pattern, replacement)
    }
  }
  if (translated !== normalized) return value.replace(normalized, translated)
  return value
}

function translateTextNode(node: Text, language: Language) {
  const current = node.nodeValue ?? ''
  const known = textOriginals.get(node)
  // Узел мог получить новый текст от React (например, подпись переключилась с
  // «ИИ Отключен» на «ИИ Включен») — тогда исходник берём из текущего значения,
  // иначе перевод навсегда застыл бы на первом варианте.
  const isOurTranslation = known != null && current === known.translated

  if (language === 'ru') {
    if (isOurTranslation) node.nodeValue = known.original
    return
  }

  const original = isOurTranslation ? known.original : current
  const next = translateValue(original, language)
  if (next !== original) {
    textOriginals.set(node, { original, translated: next })
    if (current !== next) node.nodeValue = next
  } else if (known) {
    textOriginals.delete(node)
  }
}

function translateElementAttrs(element: Element, language: Language) {
  for (const attr of ATTRS) {
    const marker = `data-i18n-original-${attr}`
    const stored = element.getAttribute(marker)
    const current = element.getAttribute(attr)
    if (language === 'ru') {
      if (stored != null) {
        element.setAttribute(attr, stored)
        element.removeAttribute(marker)
      }
      continue
    }
    const isOurTranslation = stored != null && current === translateValue(stored, language)
    const original = isOurTranslation ? stored : current
    if (!original) continue
    const next = translateValue(original, language)
    if (next !== original) {
      if (stored !== original) element.setAttribute(marker, original)
      if (current !== next) element.setAttribute(attr, next)
    } else if (stored != null) {
      element.removeAttribute(marker)
    }
  }
}

function walk(root: ParentNode, language: Language) {
  if (root instanceof Element) translateElementAttrs(root, language)

  const attrWalker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT)
  let attrNode = attrWalker.nextNode()
  while (attrNode) {
    translateElementAttrs(attrNode as Element, language)
    attrNode = attrWalker.nextNode()
  }

  const textWalker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement
      if (!parent) return NodeFilter.FILTER_REJECT
      if (['SCRIPT', 'STYLE', 'TEXTAREA', 'INPUT'].includes(parent.tagName)) return NodeFilter.FILTER_REJECT
      return /[А-Яа-яЁё]/.test(node.nodeValue ?? '') || textOriginals.has(node as Text)
        ? NodeFilter.FILTER_ACCEPT
        : NodeFilter.FILTER_SKIP
    },
  })
  let textNode = textWalker.nextNode()
  while (textNode) {
    translateTextNode(textNode as Text, language)
    textNode = textWalker.nextNode()
  }
}

export function applyRuntimeTranslations(language: Language) {
  if (typeof window === 'undefined' || typeof document === 'undefined' || !document.body) return
  const runtimeWindow = window as RuntimeWindow
  runtimeWindow[OBSERVER_KEY]?.disconnect()

  const run = () => walk(document.body, language)
  run()

  if (language !== 'ru') {
    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === 'characterData') {
          translateTextNode(mutation.target as Text, language)
          continue
        }
        if (mutation.type === 'attributes') {
          translateElementAttrs(mutation.target as Element, language)
          continue
        }
        mutation.addedNodes.forEach((node) => {
          if (node.nodeType === Node.TEXT_NODE) translateTextNode(node as Text, language)
          else if (node instanceof Element) walk(node, language)
        })
      }
    })
    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: [...ATTRS],
    })
    runtimeWindow[OBSERVER_KEY] = observer
  }
}
