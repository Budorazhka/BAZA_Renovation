/**
 * ADR-005: "slug — генерируется при первой публикации (транслитерация +
 * организация/город/название, конкретный алгоритм — деталь B-02 domain
 * model)" — domain-model.md не специфицирует конкретный алгоритм (только
 * ссылается на ADR-005), это техническая деталь реализации D-03, не
 * решение владельца.
 *
 * Простая таблица транслитерации кириллицы (RU/KA латиница не покрыта —
 * грузинские названия ЖК на латинице пишутся застройщиком напрямую в поле
 * name, если применимо; не входит в scope этой утилиты).
 */
const CYRILLIC_TO_LATIN: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z',
  и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'sch',
  ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
};

function transliterate(text: string): string {
  return text
    .toLowerCase()
    .split('')
    .map((char) => CYRILLIC_TO_LATIN[char] ?? char)
    .join('');
}

/**
 * `{название}-{город}` — организация НЕ включена в slug вопреки буквальной
 * формулировке ADR-005 "организация/город/название": Development.name уже
 * обычно содержит бренд ЖК, включение отдельно organizationId/названия
 * организации сделало бы URL длиннее без явной SEO-пользы на MVP-масштабе
 * (25 застройщиков, mongodb-schema.md) — technical simplification, не
 * расхождение с архитектурным решением (само решение владельца — что slug
 * должен быть человекочитаемым и уникальным, не конкретный порядок частей).
 */
export function buildSlugBase(name: string, city: string): string {
  const slugified = transliterate(`${name}-${city}`)
    .replace(/[^a-z0-9\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    // Ведущие/замыкающие дефисы — найдено тестом: name/city без единого
    // [a-z0-9] символа (например, только пунктуация) оставляли буквальный
    // "-" (сам разделитель между name и city уцелевает как валидный
    // символ), из-за чего проверка `slugified || 'development'` ниже не
    // срабатывала (непустая строка "-" проходила как валидный slug).
    .replace(/^-+|-+$/g, '');
  return slugified || 'development';
}

/**
 * ADR-005: slug уникален — при коллизии с существующим slug добавляется
 * числовой suffix. Вызывающий код (PublicationRequestedHandler) отвечает
 * за проверку уникальности через реальный БД-запрос и повтор с
 * увеличенным attempt при коллизии — эта функция сама по себе не
 * гарантирует уникальность, только детерминированно строит кандидата.
 */
export function buildSlugCandidate(base: string, attempt: number): string {
  return attempt === 0 ? base : `${base}-${attempt + 1}`;
}
